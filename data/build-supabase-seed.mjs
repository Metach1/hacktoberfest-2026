/**
 * Generate `supabase/seed.sql` from the SAME fictional data the app uses, so
 * the database mirrors the current demo exactly. Reuses the athlete adapter and
 * the seed-post builder; every row is marked `seeded = true` so it can be
 * removed before launch with `supabase/seed_teardown.sql`.
 *
 * Run: node data/build-supabase-seed.mjs
 */
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { adaptAthletes } from "./athlete-adapter.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "..");

/** SQL-escape a string literal (single quotes doubled); null-safe. */
function s(v) {
  if (v === null || v === undefined) return "null";
  return `'${String(v).replace(/'/g, "''")}'`;
}
function n(v) {
  return v === null || v === undefined || v === "" ? "null" : Number(v);
}
function b(v) {
  return v ? "true" : "false";
}

async function main() {
  const athletesJson = JSON.parse(await readFile(join(root, "data", "athletes.json"), "utf8"));
  const athletes = adaptAthletes(athletesJson.athletes);

  const lines = [];
  lines.push("-- Generated by data/build-supabase-seed.mjs — DO NOT EDIT BY HAND.");
  lines.push("-- Fictional demo data. Every row carries seeded = true.");
  lines.push("-- Run AFTER 0006_full_backend.sql. Idempotent via upsert on id.");
  lines.push("");

  // --- athletes --------------------------------------------------------------
  lines.push("insert into public.athletes");
  lines.push(
    "  (id, name, sport, location, region_code, region, image, bio, achievement, verified, funding_goal, base_raised, base_supporters, seeded)",
  );
  lines.push("values");
  const athleteRows = athletes.map((a) => {
    return `  (${a.id}, ${s(a.name)}, ${s(a.sport)}, ${s(a.location)}, ${s(a.regionCode)}, ${s(a.region)}, ${s(a.image)}, ${s(a.bio)}, ${s(a.achievement)}, ${b(a.verified)}, ${n(a.goal)}, ${n(a.raised)}, ${n(a.supporters)}, true)`;
  });
  lines.push(athleteRows.join(",\n"));
  lines.push(
    "on conflict (id) do update set name = excluded.name, sport = excluded.sport, " +
      "location = excluded.location, region_code = excluded.region_code, region = excluded.region, " +
      "image = excluded.image, bio = excluded.bio, achievement = excluded.achievement, " +
      "verified = excluded.verified, funding_goal = excluded.funding_goal, " +
      "base_raised = excluded.base_raised, base_supporters = excluded.base_supporters, seeded = true;",
  );
  lines.push("");

  // --- seed posts + comments -------------------------------------------------
  // Showcase posts attached to CATALOG athletes (catalog_athlete_id). These are
  // owner-less showcase rows (owner_id null), read-only, removed at launch.
  const day = 86_400_000;
  const now = Date.now();
  const seedPosts = [
    { athlete: athletes[0]?.id ?? 1, text: "One step closer to nationals — this week's time trial was a new personal best. Thank you for helping me access better recovery and coaching.", daysAgo: 3, comments: [["Jamie", "So proud of you! Keep flying 🇵🇭"], [athletes[1]?.name ?? "A teammate", "Let's go! Inspiring work."]] },
    { athlete: athletes[0]?.id ?? 1, text: "Recovery, reset, repeat. Rest days are part of the grind too.", daysAgo: 7, comments: [["Carlo M.", "Rest well, champ."]] },
    { athlete: athletes[1]?.id ?? 2, text: "Sparring went well today. Felt sharp and fast. Grateful for every supporter in my corner.", daysAgo: 1, comments: [] },
    { athlete: athletes[2]?.id ?? 3, text: "New shoes, new goals. Chasing a spot on the national team this season.", daysAgo: 5, comments: [["Nina A.", "Rooting for you!"]] },
  ];

  lines.push("-- Clear previously seeded showcase posts/comments so re-running is idempotent.");
  lines.push("delete from public.comments where seeded;");
  lines.push("delete from public.posts where seeded;");
  lines.push("");
  lines.push("-- Seed showcase posts (+ comments). Owner-less, attached to catalog athletes.");
  lines.push("do $$");
  lines.push("declare pid uuid;");
  lines.push("begin");
  for (const p of seedPosts) {
    const created = new Date(now - p.daysAgo * day).toISOString();
    lines.push(
      `  insert into public.posts (catalog_athlete_id, content, created_at, seeded) values (${p.athlete}, ${s(p.text)}, ${s(created)}, true) returning id into pid;`,
    );
    p.comments.forEach(([name, text], i) => {
      const cCreated = new Date(now - p.daysAgo * day + (i + 1) * 3_600_000).toISOString();
      lines.push(
        `  insert into public.comments (post_id, owner_id, author_name, content, created_at, seeded) values (pid, null, ${s(name)}, ${s(text)}, ${s(cCreated)}, true);`,
      );
    });
  }
  lines.push("end $$;");
  lines.push("");

  // --- seed QR codes for the first catalog athlete ---------------------------
  const first = athletes[0];
  if (first) {
    lines.push("delete from public.qr_codes where seeded;");
    lines.push("-- Seed showcase QR codes for a catalog athlete (owner-less).");
    lines.push("insert into public.qr_codes (catalog_athlete_id, method, label, image, seeded) values");
    lines.push(
      `  (${first.id}, 'GCash', 'J. Santos · 0917•••1234', '/athlete-placeholder.svg', true),`,
    );
    lines.push(
      `  (${first.id}, 'Maya', 'J. Santos · 0917•••1234', '/athlete-placeholder.svg', true);`,
    );
    lines.push("");
  }

  await writeFile(join(root, "supabase", "seed.sql"), lines.join("\n") + "\n", "utf8");
  console.log(`Wrote supabase/seed.sql (${athletes.length} athletes, ${seedPosts.length} posts).`);

  // Teardown script.
  const teardown = [
    "-- Remove ALL seeded showcase data. Safe to run before real launch.",
    "-- Order respects FKs (donations/qr/comments/reactions reference posts/athletes).",
    "delete from public.donations where catalog_athlete_id in (select id from public.athletes where seeded);",
    "delete from public.qr_codes where seeded or catalog_athlete_id in (select id from public.athletes where seeded);",
    "delete from public.comments where seeded;",
    "delete from public.posts where seeded;",
    "delete from public.athletes where seeded;",
    "",
  ].join("\n");
  await writeFile(join(root, "supabase", "seed_teardown.sql"), teardown, "utf8");
  console.log("Wrote supabase/seed_teardown.sql");
}

main().catch((e) => {
  console.error(e);
  process.exitCode = 1;
});
